/// A labelled on/off switch; the whole row toggles it.
fn switch(
    id: &'static str,
    label: &str,
    detail: Option<&str>,
    on: bool,
    t: Theme,
    click: impl Fn(&ClickEvent, &mut Window, &mut App) + 'static,
) -> Stateful<Div> {
    div()
        .id(id)
        .role(Role::Switch)
        .aria_label(label.to_string())
        .aria_toggled(toggled(on))
        .when_some(detail, |d, text| d.aria_description(text.to_string()))
        .flex()
        .items_center()
        .gap(px(sp::L))
        .p(px(sp::S))
        .rounded(px(10.))
        .with_focus_ring(t)
        .hover(|s| s.bg(rgb(t.surface)))
        .child(
            div()
                .flex_1()
                .min_w_0()
                .flex()
                .flex_col()
                .gap(px(2.))
                .child(
                    div()
                        .font_weight(FontWeight::MEDIUM)
                        .child(label.to_string()),
                )
                .children(detail.map(|text| secondary(text, t))),
        )
        .child(
            div()
                .flex_none()
                .w(px(36.))
                .h(px(20.))
                .p(px(2.))
                .rounded_full()
                .bg(rgb(if on { t.work } else { t.idle }))
                .flex()
                .when(on, |d| d.justify_end())
                .child(div().size(px(16.)).rounded_full().bg(rgb(ON_RIBBON))),
        )
        .on_click(click)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn view() -> crate::phones::View {
        crate::phones::View {
            available: true,
            ..Default::default()
        }
    }

    #[test]
    fn guide_hidden_without_bridge() {
        assert!(!guide_shown(&crate::phones::View::default()));
    }

    #[test]
    fn guide_follows_pairings_and_pending() {
        assert!(guide_shown(&view()));
        let mut paired = crate::phones::View {
            phones: vec![Phone {
                id: "a".into(),
                name: Some("Work iPhone".into()),
                state: State::Paired,
                code: None,
                last_seen_ms: Some(0),
                direct: true,
            }],
            ..view()
        };
        assert!(!guide_shown(&paired));
        // Removing the last phone brings the guide back.
        paired.phones.clear();
        assert!(guide_shown(&paired));
    }

    #[test]
    fn guide_hidden_while_pairing() {
        let mut pending = crate::phones::View {
            pending: Some(Started {
                id: "fixture".into(),
                link: String::new(),
                expires_at_ms: 60_000,
                qr: Qr {
                    size: 25,
                    dark: vec![false; 25 * 25],
                },
            }),
            ..view()
        };
        assert!(!guide_shown(&pending));
        // Cancelling or expiring a pairing brings the guide back.
        pending.pending = None;
        assert!(guide_shown(&pending));
    }

    #[test]
    fn app_store_qr_is_square_and_has_finder_patterns() {
        let qr = app_store_qr();
        // A QR symbol is 21 + 4k modules; CoreImage adds a 1-module margin on each side.
        assert!(
            qr.size >= 23 && (qr.size - 2 - 21).is_multiple_of(4),
            "size {}",
            qr.size
        );
        assert_eq!(qr.dark.len(), qr.size * qr.size);
        // Top-left finder: the corner just inside the 1-module margin is dark,
        // the margin itself is light.
        let at = |x: usize, y: usize| qr.dark[y * qr.size + x];
        assert!(!at(0, 0));
        assert!(at(1, 1) && at(7, 1) && at(1, 7));
        assert!(at(qr.size - 2, 1) && at(1, qr.size - 2));
    }

    #[test]
    fn app_store_url_is_the_listing() {
        assert_eq!(
            APP_STORE_URL,
            "https://apps.apple.com/app/agentpulse/id6835137307"
        );
    }
}
