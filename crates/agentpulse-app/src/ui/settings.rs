pub(super) fn app_store_qr() -> crate::phones::Qr {
    let rows: Vec<_> = APP_STORE_QR
        .split('\n')
        .filter(|row| !row.is_empty())
        .collect();
    crate::phones::Qr {
        size: rows.len(),
        dark: rows
            .iter()
            .flat_map(|row| row.chars().map(|c| c == '#'))
            .collect(),
    }
}

/// One click handler that calls `f` on the hub, reading its state at click time.
fn on_hub(
    entity: &Entity<Hub>,
    f: impl Fn(&mut Hub, &mut Context<Hub>) + 'static,
) -> impl Fn(&ClickEvent, &mut Window, &mut App) + 'static {
    let entity = entity.clone();
    move |_, _, cx| entity.update(cx, |h, cx| f(h, cx))
}

pub(super) fn screen(
    hub: &Hub,
    entity: &Entity<Hub>,
    t: Theme,
    scroll: &gpui::ScrollHandle,
) -> impl IntoElement {
    // The whole page scrolls, release notes and all, as Usage does.
    div()
        .id("settings")
        .track_scroll(scroll)
        .flex_1()
        .min_h_0()
        .overflow_y_scroll()
        .px(px(CONTENT_PAD))
        .pt(px(sp::M))
        .pb(px(sp::XL))
        .flex()
        .flex_col()
        .child(heading(rust_i18n::t!("settings.title").to_string()))
        .child(agents_card(hub, entity, t).mt(px(sp::XL)))
        .child(animation_card(hub, entity, t).mt(px(sp::L)))
        .child(cleanup_card(hub, entity, t).mt(px(sp::L)))
        .child(updates_card(hub, entity, t).mt(px(sp::L)))
}

fn agents_card(hub: &Hub, entity: &Entity<Hub>, t: Theme) -> Div {
    let a = hub.settings.agents();
    let rows = Provider::ALL.map(|p| {
        switch(
            p.as_str(),
            p.label(),
            (!detected(p))
                .then(|| rust_i18n::t!("settings.not_detected").to_string())
                .as_deref(),
            !a.is_hidden(p),
            t,
            on_hub(entity, move |h, cx| {
                h.settings.set_hidden(p, !h.settings.agents().is_hidden(p));
                // Wakes the collector, so every surface follows at once.
                cx.global::<Shared>().details.send(Command::Refresh).ok();
                cx.notify();
            }),
        )
    });
    card(t)
        .max_w(px(CARD_MAX_W))
        .gap(px(sp::M))
        .child(card_title(&rust_i18n::t!("settings.agents")))
        .children(rows)
        .child(secondary(&rust_i18n::t!("settings.agents_detail"), t).px(px(sp::S)))
}

/// Whether the agent's data folder (its adapter's default root) exists: one
/// metadata call, made when the screen renders.
fn detected(p: Provider) -> bool {
    match p {
        Provider::ClaudeCode => ClaudeCodeAdapter::default_root(),
        Provider::Codex => CodexAdapter::default_root(),
        Provider::OpenCode => OpenCodeAdapter::default_root(),
        Provider::Grok => GrokAdapter::default_root(),
        Provider::Qwen => QwenAdapter::default_root(),
        Provider::Gemini => GeminiAdapter::default_root(),
    }
    .is_some_and(|root| root.exists())
}

fn animation_card(hub: &Hub, entity: &Entity<Hub>, t: Theme) -> Div {
    let a = hub.settings.animation();
    // The speed options follow what is in effect, not just the stored choice.
    let live = hub.motion.enabled;
    let shown = SPEEDS.into_iter().min_by(|x, y| {
        (x - hub.motion.speed)
            .abs()
            .total_cmp(&(y - hub.motion.speed).abs())
    });
    let why = if reduce_motion() {
        Some(rust_i18n::t!("settings.reduce_motion").to_string())
    } else if hub::env_overrides_animation() {
        Some(rust_i18n::t!("settings.env_animation").to_string())
    } else {
        None
    };
    let speeds = SPEEDS.iter().enumerate().map(|(i, &speed)| {
        let on = shown == Some(speed);
        let label = format!("{speed}×");
        div()
            .id(("speed", i))
            .role(Role::RadioButton)
            .aria_label(label.clone())
            .aria_toggled(toggled(on))
            .px(px(sp::M))
            .py(px(sp::XS))
            .rounded(px(8.))
            .when(on, |d| d.bg(rgb(t.card)).font_weight(FontWeight::BOLD))
            .map(|d| {
                if live {
                    d.with_focus_ring(t)
                        .when(!on, |d| d.hover(|s| s.bg(rgb(t.surface))))
                        .on_click(on_hub(entity, move |h, cx| h.set_speed(speed, cx)))
                } else {
                    // Inert while the cats do not move: no focus, no click.
                    d.aria_description(rust_i18n::t!("settings.animation_off").to_string())
                        .border_1()
                        .border_color(transparent_black())
                        .text_color(rgb(t.muted))
                }
            })
            .child(label.to_string())
    });
    card(t)
        .max_w(px(CARD_MAX_W))
        .gap(px(sp::M))
        .child(card_title(&rust_i18n::t!("settings.animation")))
        .child(switch(
            "animate",
            &rust_i18n::t!("settings.animate"),
            None,
            a.enabled,
            t,
            on_hub(entity, |h, cx| h.toggle_animation(cx)),
        ))
        .child(
            div()
                .flex()
                .items_center()
                .gap(px(sp::M))
                .px(px(sp::S))
                .child(
                    div()
                        .font_weight(FontWeight::MEDIUM)
                        .when(!live, |d| d.text_color(rgb(t.muted)))
                        .child(rust_i18n::t!("settings.speed").to_string()),
                )
                .child(
                    div()
                        .id("speed")
                        .role(Role::RadioGroup)
                        .aria_label(rust_i18n::t!("settings.speed").to_string())
                        .flex()
                        .gap(px(sp::XS))
                        .p(px(3.))
                        .rounded(px(10.))
                        .bg(rgb(t.chrome))
                        .border_1()
                        .border_color(rgb(t.border))
                        .children(speeds),
                ),
        )
        .children(why.map(|w| secondary(&w, t).px(px(sp::S))))
}

fn cleanup_card(hub: &Hub, entity: &Entity<Hub>, t: Theme) -> Div {
    let c = hub.settings.cleanup();
    card(t)
        .max_w(px(CARD_MAX_W))
        .gap(px(sp::M))
        .child(card_title(&rust_i18n::t!("settings.cleanup")))
        .child(row(&rust_i18n::t!("settings.warn_after")).child(hours(
            "settings.warn_after",
            &WARN_CHOICES,
            c.warn_after_hours,
            t,
            entity,
            |c, h| c.warn_after_hours = h,
        )))
        .child(row(&rust_i18n::t!("settings.end_after")).child(hours(
            "settings.end_after",
            &CLEAN_CHOICES,
            c.clean_after_hours,
            t,
            entity,
            |c, h| c.clean_after_hours = h,
        )))
        .child(switch(
            "auto-clean",
            &rust_i18n::t!("settings.auto_clean"),
            None,
            c.auto_clean,
            t,
            on_hub(entity, |h, cx| {
                let mut c = h.settings.cleanup();
                c.auto_clean = !c.auto_clean;
                h.set_cleanup(c, cx);
            }),
        ))
        .child(secondary(&rust_i18n::t!("settings.cleanup_detail"), t).px(px(sp::S)))
}

/// A radio group of hours, styled as the Speed group; a click saves `set(c, hours)`.
fn hours(
    label: &'static str,
    choices: &[u32],
    on: u32,
    t: Theme,
    entity: &Entity<Hub>,
    set: fn(&mut Cleanup, u32),
) -> Stateful<Div> {
    let options = choices.iter().enumerate().map(|(i, &h)| {
        let chosen = h == on;
        let text = rust_i18n::t!("settings.hours", h = h).to_string();
        div()
            .id((label, i))
            .role(Role::RadioButton)
            .aria_label(text.clone())
            .aria_toggled(toggled(chosen))
            .px(px(sp::M))
            .py(px(sp::XS))
            .rounded(px(8.))
            .with_focus_ring(t)
            .map(|d| {
                if chosen {
                    d.bg(rgb(t.card)).font_weight(FontWeight::BOLD)
                } else {
                    d.hover(|s| s.bg(rgb(t.surface)))
                }
            })
            .on_click(on_hub(entity, move |hub, cx| {
                let mut c = hub.settings.cleanup();
                set(&mut c, h);
                hub.set_cleanup(c, cx);
            }))
            .child(text.to_string())
    });
    div()
        .id(label)
        .role(Role::RadioGroup)
        .aria_label(rust_i18n::t!(label).to_string())
        .flex()
        .gap(px(sp::XS))
        .p(px(3.))
        .rounded(px(10.))
        .bg(rgb(t.chrome))
        .border_1()
        .border_color(rgb(t.border))
        .children(options)
}

fn updates_card(hub: &Hub, entity: &Entity<Hub>, t: Theme) -> Div {
    let u = hub.settings.updates();
    let now = now_ms();
    let at = |ms: i64| format::start_time(ms, now);
    let status = if hub.checking {
        rust_i18n::t!("settings.checking").to_string()
    } else {
        match &hub.last_check {
            Some(Ok(Check::UpToDate)) => rust_i18n::t!(
                "settings.current",
                version = CURRENT,
                time = at(hub.checked_at_ms)
            )
            .to_string(),
            Some(Ok(Check::Available(_))) => {
                rust_i18n::t!("settings.checked", time = at(hub.checked_at_ms)).to_string()
            }
            Some(Err(e)) => rust_i18n::t!(
                "settings.check_error",
                error = e,
                time = at(hub.checked_at_ms)
            )
            .to_string(),
            // Checked in an earlier run, not yet in this one.
            None if u.last_checked_ms > 0 => {
                rust_i18n::t!("settings.last_checked", time = at(u.last_checked_ms)).to_string()
            }
            None => rust_i18n::t!("settings.never_checked").to_string(),
        }
    };
    card(t)
        .max_w(px(CARD_MAX_W))
        .gap(px(sp::M))
        .child(card_title(&rust_i18n::t!("settings.updates")))
        .child(switch(
            "auto-updates",
            &rust_i18n::t!("settings.auto_updates"),
            Some(&rust_i18n::t!("settings.auto_detail")),
            u.auto,
            t,
            on_hub(entity, |h, cx| h.toggle_auto_updates(cx)),
        ))
        .child(
            div()
                .flex()
                .items_center()
                .gap(px(sp::M))
                .px(px(sp::S))
                .child(
                    button("check-now", &rust_i18n::t!("settings.check_now"), t)
                        .on_click(on_hub(entity, |h, cx| h.check_now(cx))),
                )
                .child(div().min_w_0().text_color(rgb(t.muted)).child(status)),
        )
        .children(hub.available().map(|r| release(r, t)))
}

/// Saves the relay field's address, shown as the field normalised it; an error otherwise.
pub(super) fn save_relay(hub: &Entity<Hub>, field: &Entity<TextField>, cx: &mut App) {
    let text = field.read(cx).text().to_string();
    if hub.update(cx, |h, cx| h.save_relay(&text, cx)) {
        let saved = hub.read(cx).settings.phones().relay.unwrap_or_default();
        field.update(cx, |f, cx| f.reset(&saved, cx));
    }
}

/// Saves the key field's key to the Keychain and empties the field; true when
/// saved, else the card shows an error.
pub(super) fn save_key(hub: &Entity<Hub>, field: &Entity<TextField>, cx: &mut App) -> bool {
    let text = field.read(cx).text().to_string();
    let saved = hub.update(cx, |h, cx| h.save_relay_key(&text, cx));
    if saved {
        field.update(cx, |f, cx| f.reset("", cx));
    }
    saved
}

/// The Phones screen's controls that live in the window's view.
