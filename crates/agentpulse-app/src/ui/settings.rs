fn guide_shown(v: &crate::phones::View) -> bool {
    v.available && v.phones.is_empty() && v.pending.is_none()
}

pub(super) fn phones_screen(
    hub: &Hub,
    entity: &Entity<Hub>,
    phone: PhoneControls,
    t: Theme,
    scroll: &gpui::ScrollHandle,
) -> impl IntoElement {
    let (v, _) = hub.phone_state();
    div()
        .id("phones")
        .track_scroll(scroll)
        .flex_1()
        .min_h_0()
        .overflow_y_scroll()
        .px(px(CONTENT_PAD))
        .pt(px(sp::M))
        .pb(px(sp::XL))
        .flex()
        .flex_col()
        .child(heading(rust_i18n::t!("phones.title").to_string()))
        .when(!v.available, |d| {
            d.child(secondary(&rust_i18n::t!("phones.bundle_required"), t).mt(px(sp::XL)))
        })
        .when(v.available, |d| {
            d.child(
                if guide_shown(&v) {
                    guide_card(hub, entity, &v, t)
                } else {
                    pairing_card(hub, entity, &v, t)
                }
                .mt(px(sp::XL)),
            )
            .child(connection_card(hub, entity, phone, t).mt(px(sp::L)))
        })
}

fn phone_errors<'a>(
    hub: &'a Hub,
    v: &'a crate::phones::View,
    t: Theme,
) -> impl Iterator<Item = Div> + 'a {
    hub.phone_error
        .iter()
        .chain(&v.error)
        .map(move |e| secondary(e, t).px(px(sp::S)).text_color(rgb(t.failed)))
}

